//! Marching Cubes implementation for smooth terrain mesh generation.
//!
//! This module implements the Marching Cubes algorithm for extracting isosurfaces
//! from voxel density fields, creating smooth terrain geometry.

use super::super::grid::VoxelMesh;

/// Marching Cubes mesh generator for smooth terrain
pub struct MarchingCubes;

impl MarchingCubes {
    /// Generate smooth mesh for a chunk using Marching Cubes algorithm.
    ///
    /// # Arguments
    /// * `density_field` - 3D density field where values > 0.5 are solid
    /// * `chunk_size` - Size of the chunk (typically 16x16x16)
    ///
    /// # Returns
    /// A `VoxelMesh` with smooth geometry and computed normals
    pub fn generate_mesh(
        density_field: &[[[f32; 18]; 18]; 18],
        chunk_size: usize,
    ) -> VoxelMesh {
        // Marching Cubes implementation currently requires chunk_size=16
        // because density_field is hardcoded to [18][18][18] (16+2 padding)
        assert_eq!(
            chunk_size, 16,
            "MarchingCubes currently only supports chunk_size=16, got {}",
            chunk_size
        );

        let mut vertices = Vec::new();
        let mut normals = Vec::new();
        let mut indices = Vec::new();
        let mut ambient_occlusion = Vec::new();

        // Marching cubes processes cells between density samples
        // density_field is [18][18][18] with samples at indices 0..17
        // Blocks are stored at samples [1..17] (16 blocks)
        // We want to process the 16 cells that cover these blocks
        // Cell at index i uses corners from samples [i] to [i+1]
        // So we process cells 1..17 (16 cells), accessing samples up to [17]
        for x in 1..=chunk_size {
            for y in 1..=chunk_size {
                for z in 1..=chunk_size {
                    Self::process_cell(
                        density_field,
                        x,
                        y,
                        z,
                        &mut vertices,
                        &mut normals,
                        &mut indices,
                        &mut ambient_occlusion,
                    );
                }
            }
        }

        VoxelMesh {
            vertices,
            normals,
            indices,
            ambient_occlusion,
        }
    }

    /// Process a single cell in the marching cubes algorithm
    fn process_cell(
        density_field: &[[[f32; 18]; 18]; 18],
        x: usize,
        y: usize,
        z: usize,
        vertices: &mut Vec<[f32; 3]>,
        normals: &mut Vec<[f32; 3]>,
        indices: &mut Vec<u32>,
        ambient_occlusion: &mut Vec<f32>,
    ) {
        // Get the 8 corner values for this cube
        let corners = [
            density_field[x][y][z],
            density_field[x + 1][y][z],
            density_field[x + 1][y][z + 1],
            density_field[x][y][z + 1],
            density_field[x][y + 1][z],
            density_field[x + 1][y + 1][z],
            density_field[x + 1][y + 1][z + 1],
            density_field[x][y + 1][z + 1],
        ];

        // Compute cube index (which corners are inside/outside)
        let mut cube_index = 0u8;
        for (i, &corner) in corners.iter().enumerate() {
            if corner > 0.5 {
                cube_index |= 1 << i;
            }
        }

        // Skip if cube is entirely inside or outside
        if cube_index == 0 || cube_index == 255 {
            return;
        }

        // Get triangulation for this cube configuration
        let edge_flags = EDGE_TABLE[cube_index as usize];
        if edge_flags == 0 {
            return;
        }

        // Find vertices along edges where surface crosses
        let mut edge_vertices = [[0.0f32; 3]; 12];
        let iso_level = 0.5;

        for i in 0..12 {
            if edge_flags & (1 << i) != 0 {
                let (v0_idx, v1_idx) = EDGE_CONNECTIONS[i];
                let v0 = Self::corner_position(x, y, z, v0_idx);
                let v1 = Self::corner_position(x, y, z, v1_idx);
                let d0 = corners[v0_idx];
                let d1 = corners[v1_idx];

                // Linear interpolation
                let t = if (d1 - d0).abs() < 0.00001 {
                    0.5
                } else {
                    (iso_level - d0) / (d1 - d0)
                };

                edge_vertices[i] = [
                    v0[0] + t * (v1[0] - v0[0]),
                    v0[1] + t * (v1[1] - v0[1]),
                    v0[2] + t * (v1[2] - v0[2]),
                ];
            }
        }

        // Generate triangles from the triangle table
        let tri_indices = &TRI_TABLE[cube_index as usize];

        for tri_edge_indices in tri_indices.chunks(3) {
            if tri_edge_indices[0] == 255 {
                break;
            }

            // Record base vertex for this triangle
            let base_vertex = vertices.len() as u32;

            // Add the three vertices of this triangle
            for &edge_idx in tri_edge_indices {
                let vert = edge_vertices[edge_idx as usize];
                vertices.push(vert);

                // Compute normal from density gradient
                let normal = Self::compute_normal(density_field, vert[0], vert[1], vert[2]);
                normals.push(normal);

                // Smooth terrain doesn't need complex AO - use density as simple approximation
                // Lower density (near surface) = less occlusion
                let density = Self::sample_density(density_field, vert[0], vert[1], vert[2]);
                let ao = 0.6 + (1.0 - density) * 0.4; // Range [0.6, 1.0]
                ambient_occlusion.push(ao);
            }

            // Add indices (counter-clockwise winding)
            indices.push(base_vertex + 0);
            indices.push(base_vertex + 1);
            indices.push(base_vertex + 2);
        }
    }

    /// Sample density at a specific position using trilinear interpolation
    fn sample_density(field: &[[[f32; 18]; 18]; 18], x: f32, y: f32, z: f32) -> f32 {
        let x0 = x.floor() as usize;
        let y0 = y.floor() as usize;
        let z0 = z.floor() as usize;
        let x1 = (x0 + 1).min(17);
        let y1 = (y0 + 1).min(17);
        let z1 = (z0 + 1).min(17);

        let fx = x - x0 as f32;
        let fy = y - y0 as f32;
        let fz = z - z0 as f32;

        // Trilinear interpolation
        let c000 = field[x0][y0][z0];
        let c001 = field[x0][y0][z1];
        let c010 = field[x0][y1][z0];
        let c011 = field[x0][y1][z1];
        let c100 = field[x1][y0][z0];
        let c101 = field[x1][y0][z1];
        let c110 = field[x1][y1][z0];
        let c111 = field[x1][y1][z1];

        let c00 = c000 * (1.0 - fx) + c100 * fx;
        let c01 = c001 * (1.0 - fx) + c101 * fx;
        let c10 = c010 * (1.0 - fx) + c110 * fx;
        let c11 = c011 * (1.0 - fx) + c111 * fx;

        let c0 = c00 * (1.0 - fy) + c10 * fy;
        let c1 = c01 * (1.0 - fy) + c11 * fy;

        c0 * (1.0 - fz) + c1 * fz
    }

    /// Get position of a cube corner
    fn corner_position(x: usize, y: usize, z: usize, corner_idx: usize) -> [f32; 3] {
        let x = x as f32;
        let y = y as f32;
        let z = z as f32;

        match corner_idx {
            0 => [x, y, z],
            1 => [x + 1.0, y, z],
            2 => [x + 1.0, y, z + 1.0],
            3 => [x, y, z + 1.0],
            4 => [x, y + 1.0, z],
            5 => [x + 1.0, y + 1.0, z],
            6 => [x + 1.0, y + 1.0, z + 1.0],
            7 => [x, y + 1.0, z + 1.0],
            _ => [x, y, z],
        }
    }

    /// Compute surface normal using central differences on the density field
    fn compute_normal(
        density_field: &[[[f32; 18]; 18]; 18],
        x: f32,
        y: f32,
        z: f32,
    ) -> [f32; 3] {
        let _h = 0.5; // Step size for gradient (reserved for future refinement)

        let xi = x.floor() as usize;
        let yi = y.floor() as usize;
        let zi = z.floor() as usize;

        // Sample density at neighboring positions (with bounds checking)
        let dx = if xi > 0 && xi < 16 {
            density_field[xi + 1][yi][zi] - density_field[xi - 1][yi][zi]
        } else {
            0.0
        };

        let dy = if yi > 0 && yi < 16 {
            density_field[xi][yi + 1][zi] - density_field[xi][yi - 1][zi]
        } else {
            0.0
        };

        let dz = if zi > 0 && zi < 16 {
            density_field[xi][yi][zi + 1] - density_field[xi][yi][zi - 1]
        } else {
            0.0
        };

        // Normalize the gradient
        let len = (dx * dx + dy * dy + dz * dz).sqrt();
        if len < 0.0001 {
            [0.0, 1.0, 0.0] // Default to up if gradient is zero
        } else {
            [-dx / len, -dy / len, -dz / len] // Negative because we want outward normal
        }
    }

    /// Convert voxel block data to density field
    ///
    /// This creates a 18x18x18 field (16x16x16 chunk + 1 padding on each side)
    /// for proper gradient computation at boundaries.
    pub fn create_density_field(
        blocks: &[[[bool; 16]; 16]; 16],
    ) -> [[[f32; 18]; 18]; 18] {
        let mut field = [[[0.0f32; 18]; 18]; 18];

        for x in 0..16 {
            for y in 0..16 {
                for z in 0..16 {
                    // Center the blocks in the field (skip padding)
                    field[x + 1][y + 1][z + 1] = if blocks[x][y][z] { 1.0 } else { 0.0 };
                }
            }
        }

        field
    }
}

